begin
 if actor is null or not public.by43_is_admin() then raise exception 'Administrator access required' using errcode='42501'; end if;
 if (p_note is null and p_recommended is null) or char_length(p_note)>1000 or not exists(select 1 from public.by43_public_catalog c where c.city_slug=p_city and c.place_id=p_place_id) then
